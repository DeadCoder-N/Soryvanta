import Link from 'next/link'
import Image from 'next/image'
import { searchListings } from '@brisvora/api'
import { formatPrice } from '@brisvora/shared'
import { auth } from '@/auth'
import Navbar from '@/components/Navbar'
import Footer from '@/components/Footer'
import SearchBar from '@/components/SearchBar'

interface SearchParams {
  city?: string
  minPrice?: string
  maxPrice?: string
  type?: string
  bedrooms?: string
  page?: string
}

type SearchListing = {
  id: string
  slug: string
  title: string
  city: string
  price: number
  type: string
  bedrooms: number | null
  bathrooms: number | null
  images: Array<{ url: string }>
  analytics: { viewCount: number } | null
}

export default async function HomePage({ searchParams }: { searchParams: Promise<SearchParams> }) {
  const sp = await searchParams
  const session = await auth()
  const listings = await searchListings({
    city: sp.city,
    minPrice: sp.minPrice ? Number(sp.minPrice) : undefined,
    maxPrice: sp.maxPrice ? Number(sp.maxPrice) : undefined,
    type: sp.type,
    bedrooms: sp.bedrooms ? Number(sp.bedrooms) : undefined,
    page: sp.page ? Number(sp.page) : 1,
  })

  const hasFilters = sp.city || sp.type || sp.bedrooms || sp.minPrice || sp.maxPrice

  return (
    <div style={{ background: 'var(--linen)', minHeight: '100vh' }}>
      <Navbar />

      {/* ── HERO ── */}
      <section style={{ background: 'var(--warm-white)', padding: '64px 0 56px' }}>
        <div style={{ maxWidth: '1200px', margin: '0 auto', padding: '0 1.5rem' }}>
          <div className="hero-grid" style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '80px', alignItems: 'flex-end' }}>
            <div>
              <p className="animate-fade-up" style={{ fontSize: '0.65rem', color: 'var(--mauve)', letterSpacing: '0.25em', textTransform: 'uppercase', marginBottom: '20px' }}>
                AI-Powered Real Estate Platform
              </p>
              <h1 className="animate-fade-up delay-100" style={{ fontFamily: 'var(--font-serif)', fontSize: 'clamp(2.2rem, 4.5vw, 4rem)', color: 'var(--ink)', lineHeight: 1.08, fontWeight: 400 }}>
                Bespoke Listings<br />
                <em style={{ fontStyle: 'italic', color: 'var(--logo-gold)' }}>Defined by</em><br />
                Intelligence
              </h1>
            </div>
            <div className="animate-fade-up delay-200">
              <p style={{ fontSize: '0.95rem', color: 'var(--ink-soft)', lineHeight: 1.85, marginBottom: '36px', maxWidth: '380px' }}>
                Send property details via WhatsApp and receive a professionally crafted listing page — generated by AI, ready to share in minutes.
              </p>
              <div style={{ display: 'flex', alignItems: 'center', gap: '24px', flexWrap: 'wrap' }}>
                <Link href={session?.user ? '/dashboard' : '/register'}
                  className="btn-press"
                  style={{
                    background: 'var(--logo-gold)', color: 'var(--warm-white)',
                    fontSize: '0.72rem', letterSpacing: '0.14em', textTransform: 'uppercase',
                    padding: '14px 32px', textDecoration: 'none',
                  }}>
                  {session?.user ? 'Go to Dashboard' : 'Get Started Free'}
                </Link>
                <span style={{ fontSize: '0.8rem', color: 'var(--ink-muted)' }}>— No setup needed</span>
              </div>
            </div>
          </div>

          {/* Stats */}
          <div className="stats-grid animate-fade-up delay-300" style={{ borderTop: '1px solid var(--linen-dk)', marginTop: '56px', paddingTop: '36px', display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '0' }}>
            {[
              { num: '2 min', label: 'Average listing creation time' },
              { num: 'AI', label: 'Powered property descriptions' },
              { num: '100%', label: 'WhatsApp native workflow' },
            ].map((s, i) => (
              <div key={s.label} style={{ paddingRight: '32px', borderRight: i < 2 ? '1px solid var(--linen-dk)' : 'none', paddingLeft: i > 0 ? '32px' : '0', marginBottom: '8px' }}>
                <p style={{ fontFamily: 'var(--font-serif)', fontSize: '2rem', color: 'var(--ink)', fontWeight: 400 }}>{s.num}</p>
                <p style={{ fontSize: '0.75rem', color: 'var(--ink-muted)', letterSpacing: '0.05em', marginTop: '6px' }}>{s.label}</p>
              </div>
            ))}
          </div>
        </div>
      </section>

      {/* ── SEARCH BAR ── */}
      <section style={{ background: 'var(--bark)', padding: '28px 0' }}>
        <div style={{ maxWidth: '1200px', margin: '0 auto', padding: '0 1.5rem' }}>
          <SearchBar city={sp.city} type={sp.type} bedrooms={sp.bedrooms} minPrice={sp.minPrice} />
        </div>
      </section>

      {/* ── LISTINGS ── */}
      <section style={{ maxWidth: '1200px', margin: '0 auto', padding: '64px 1.5rem' }}>
        <div className="animate-fade-up" style={{ display: 'flex', alignItems: 'flex-end', justifyContent: 'space-between', marginBottom: '40px', flexWrap: 'wrap', gap: '12px' }}>
          <div>
            <p style={{ fontSize: '0.65rem', color: 'var(--logo-gold)', letterSpacing: '0.22em', textTransform: 'uppercase', marginBottom: '10px' }}>
              {hasFilters ? 'Search Results' : 'Featured Properties'}
            </p>
            <h2 style={{ fontFamily: 'var(--font-serif)', fontSize: '2rem', color: 'var(--ink)', fontWeight: 400 }}>
              {listings.length > 0 ? `${listings.length} Properties Available` : 'No Properties Found'}
            </h2>
          </div>
          {hasFilters && (
            <Link href="/"
              className="btn-press"
              style={{
                fontSize: '0.72rem', color: 'var(--ink-soft)', letterSpacing: '0.1em',
                textTransform: 'uppercase', textDecoration: 'none',
                borderBottom: '1px solid var(--ink-muted)', paddingBottom: '2px',
              }}>
              Clear all
            </Link>
          )}
        </div>

        {listings.length === 0 ? (
          <div className="animate-fade-in" style={{ textAlign: 'center', padding: '80px 0' }}>
            <p style={{ fontFamily: 'var(--font-serif)', fontSize: '1.5rem', color: 'var(--ink-soft)', marginBottom: '12px' }}>
              No listings found
            </p>
            <p style={{ fontSize: '0.85rem', color: 'var(--ink-muted)' }}>Try adjusting your filters</p>
          </div>
        ) : (
          <div className="listings-grid" style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: '36px' }}>
            {listings.map((p: SearchListing, idx: number) => (
              <Link key={p.id} href={`/property/${p.slug}`}
                style={{ textDecoration: 'none', display: 'block' }}
                className={`group card-lift animate-fade-up delay-${Math.min(idx * 100, 500) || 100}`}>
                <div style={{ position: 'relative', height: idx % 5 === 0 ? '300px' : '240px', background: 'var(--linen-md)', overflow: 'hidden' }}>
                  {p.images[0] ? (
                    <Image
                      src={p.images[0].url}
                      alt={p.title}
                      fill
                      style={{ objectFit: 'cover', transition: 'transform 0.7s cubic-bezier(0.22,1,0.36,1)' }}
                      className="group-hover:scale-105"
                    />
                  ) : (
                    <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', height: '100%', color: 'var(--ink-muted)', fontSize: '0.7rem', letterSpacing: '0.15em', textTransform: 'uppercase' }}>
                      No Image
                    </div>
                  )}
                  <div style={{
                    position: 'absolute', top: '14px', left: '14px',
                    background: 'var(--warm-white)', color: 'var(--ink)',
                    fontSize: '0.6rem', letterSpacing: '0.18em', textTransform: 'uppercase',
                    padding: '4px 10px',
                  }}>
                    {p.type}
                  </div>
                </div>

                <div style={{ padding: '16px 0 12px', borderBottom: '1px solid var(--linen-dk)' }}>
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
                    <p style={{ fontSize: '0.68rem', color: 'var(--ink-muted)', letterSpacing: '0.14em', textTransform: 'uppercase' }}>
                      {p.city}
                    </p>
                    <p style={{ fontSize: '0.68rem', color: 'var(--ink-muted)' }}>
                      {p.analytics?.viewCount ?? 0} views
                    </p>
                  </div>
                  <h3 style={{
                    fontFamily: 'var(--font-serif)', fontSize: '1.05rem', color: 'var(--ink)',
                    fontWeight: 400, lineHeight: 1.4, marginBottom: '10px',
                    transition: 'color 0.2s',
                  }}
                    className="line-clamp-2 group-hover:text-[#C09030]">
                    {p.title}
                  </h3>
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                    <span style={{ fontSize: '1rem', fontWeight: 600, color: 'var(--ink)' }}>
                      {formatPrice(p.price)}
                    </span>
                    {(p.bedrooms || p.bathrooms) && (
                      <span style={{ fontSize: '0.75rem', color: 'var(--ink-soft)' }}>
                        {p.bedrooms && `${p.bedrooms} bed`}
                        {p.bedrooms && p.bathrooms && ' · '}
                        {p.bathrooms && `${p.bathrooms} bath`}
                      </span>
                    )}
                  </div>
                </div>
              </Link>
            ))}
          </div>
        )}
      </section>

      {/* ── FAQ SECTION ── */}
      <section style={{ background: 'var(--warm-white)', padding: '72px 0', borderTop: '1px solid var(--linen-dk)' }}>
        <div style={{ maxWidth: '800px', margin: '0 auto', padding: '0 1.5rem' }}>
          <p className="animate-fade-up" style={{ fontSize: '0.65rem', color: 'var(--mauve)', letterSpacing: '0.22em', textTransform: 'uppercase', marginBottom: '12px', textAlign: 'center' }}>
            Frequently Asked Questions
          </p>
          <h2 className="animate-fade-up delay-100" style={{ fontFamily: 'var(--font-serif)', fontSize: '2rem', color: 'var(--ink)', fontWeight: 400, marginBottom: '48px', textAlign: 'center' }}>
            How Brisvora Works
          </h2>

          <div style={{ display: 'flex', flexDirection: 'column', gap: '28px' }}>
            {[
              {
                q: 'What is Brisvora?',
                a: 'Brisvora is India\'s first AI-powered property listing platform. Real estate brokers send property details via WhatsApp, and our AI instantly generates a professional, SEO-optimized listing page with a shareable URL.',
              },
              {
                q: 'How do I create a property listing?',
                a: 'Simply register on Brisvora, link your WhatsApp number in your profile, and send a message to our WhatsApp bot with your property details. You can have a guided conversation or send all details in one message — either way, your listing goes live in under 2 minutes.',
              },
              {
                q: 'Which cities in India are supported?',
                a: 'Brisvora supports property listings across all major Indian cities including Mumbai, Delhi, Bangalore, Pune, Hyderabad, Chennai, Kolkata, Jaipur, Ahmedabad, Noida, Gurgaon and more.',
              },
              {
                q: 'Is Brisvora free for brokers?',
                a: 'Yes! Creating and sharing property listings is completely free for brokers. You only need an AiSensy WhatsApp account to receive and send messages.',
              },
              {
                q: 'Can buyers contact me directly?',
                a: 'Yes. Every listing page has a WhatsApp chat button and an enquiry form. Interested buyers can reach you instantly, and all leads are tracked in your broker dashboard.',
              },
            ].map((faq, i) => (
              <div key={faq.q}
                className={`animate-fade-up delay-${(i + 1) * 100}`}
                style={{ borderBottom: '1px solid var(--linen-dk)', paddingBottom: '24px' }}>
                <h3 style={{ fontFamily: 'var(--font-serif)', fontSize: '1.1rem', color: 'var(--ink)', fontWeight: 500, marginBottom: '8px' }}>
                  {faq.q}
                </h3>
                <p style={{ fontSize: '0.85rem', color: 'var(--ink-soft)', lineHeight: 1.7 }}>
                  {faq.a}
                </p>
              </div>
            ))}
          </div>
        </div>
      </section>

      {/* ── CTA STRIP ── */}
      <section style={{ background: 'var(--bark)', padding: '80px 0' }}>
        <div className="cta-grid" style={{ maxWidth: '1200px', margin: '0 auto', padding: '0 1.5rem', display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '80px', alignItems: 'center' }}>
          <div className="animate-fade-up">
            <p style={{ fontSize: '0.65rem', color: 'var(--logo-gold-bright)', letterSpacing: '0.22em', textTransform: 'uppercase', marginBottom: '20px' }}>
              For Brokers
            </p>
            <h2 style={{ fontFamily: 'var(--font-serif)', fontSize: 'clamp(1.75rem, 3vw, 2.75rem)', color: 'var(--warm-white)', lineHeight: 1.15, fontWeight: 400 }}>
              List properties in<br />
              <em style={{ fontStyle: 'italic', color: 'var(--logo-gold-bright)' }}>minutes, not hours</em>
            </h2>
          </div>
          <div className="animate-fade-up delay-150">
            <p style={{ fontSize: '0.9rem', color: 'rgba(253,252,249,0.5)', lineHeight: 1.85, marginBottom: '32px' }}>
              Send a WhatsApp message with property details and photos. Our AI instantly generates a professional listing page with a shareable URL — no technical knowledge required.
            </p>
            <div style={{ display: 'flex', gap: '16px', alignItems: 'center', flexWrap: 'wrap' }}>
              <Link href={session?.user ? '/dashboard' : '/register'}
                className="btn-press"
                style={{
                  background: 'var(--logo-gold)', color: 'var(--warm-white)',
                  fontSize: '0.72rem', letterSpacing: '0.14em', textTransform: 'uppercase',
                  padding: '15px 36px', textDecoration: 'none',
                }}>
                {session?.user ? 'Go to Dashboard' : 'Start Free'}
              </Link>
              {!session?.user && (
                <Link href="/login"
                  className="nav-link"
                  style={{
                    fontSize: '0.72rem', color: 'rgba(255,253,245,0.45)',
                    letterSpacing: '0.1em', textTransform: 'uppercase',
                    textDecoration: 'none',
                  }}>
                  Sign in
                </Link>
              )}
            </div>
          </div>
        </div>
      </section>

      <Footer />
    </div>
  )
}
